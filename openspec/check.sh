#!/usr/bin/env bash
# OpenSpec checks of this repository (openspec/specs/openspec-workflow), run with the CLI pinned in openspec/cli.pin.
# Usage: bash openspec/check.sh [root]   (root defaults to the repository top level)
# The CLI is the global `openspec` when its version equals the pin, else `npm exec` of the pinned package;
# OPENSPEC="<command>" overrides it.
set -euo pipefail
root=${1:-$(git rev-parse --show-toplevel)}
cd "$root"
export OPENSPEC_TELEMETRY=0 DO_NOT_TRACK=1 OPENSPEC_NO_UPDATE_CHECK=1
bad=0
fail() { echo "::error::$*"; bad=1; }

[[ $(wc -l < openspec/cli.pin) -eq 1 && $(<openspec/cli.pin) =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] \
  || { echo "::error::openspec/cli.pin must be one MAJOR.MINOR.PATCH line"; exit 1; }
pin=$(<openspec/cli.pin)

if [[ -n ${OPENSPEC:-} ]]; then
  read -ra cli <<< "$OPENSPEC"
elif [[ $(openspec --version 2>/dev/null) == "$pin" ]]; then
  cli=(openspec)
else
  cli=(npm exec --yes "--package=@fission-ai/openspec@$pin" -- openspec)
fi
version=$("${cli[@]}" --version)
[[ $version == "$pin" ]] || { echo "::error::${cli[*]} is $version, openspec/cli.pin is $pin"; exit 1; }

# Strict validation of every main spec and active change; warnings count.
"${cli[@]}" validate --all --strict --no-interactive || fail "openspec validate --all --strict reports issues (above)"

# A main spec's Purpose is never the placeholder archiving leaves.
for f in openspec/specs/*/spec.md; do
  purpose=$(awk '/^## Purpose/{p=1; next} p && NF {print; exit}' "$f")
  [[ $purpose == "TBD - created by archiving change"* ]] && fail "$f: Purpose is the TBD placeholder"
done

# Every active change was created by `openspec new change`.
for d in openspec/changes/*/; do
  [[ $(basename "$d") == archive ]] && continue
  [[ -f $d.openspec.yaml ]] || fail "${d%/}: no .openspec.yaml (create changes with \`openspec new change\`)"
done

# The skills were generated by the pinned CLI.
skills=0
for f in .claude/skills/openspec-*/SKILL.md .agents/skills/openspec-*/SKILL.md; do
  [[ -f $f ]] || continue
  skills=$((skills + 1))
  grep -qE "^[[:space:]]*generatedBy: \"?$pin\"?[[:space:]]*$" "$f" \
    || fail "$f: generatedBy is not $pin (regenerate with \`openspec update --force\`)"
done
(( skills )) || fail "no OpenSpec skills under .claude/skills/ or .agents/skills/"

# Archived changes leave only [human] tasks open.
while IFS= read -r hit; do
  fail "$hit: unticked task in an archived change"
done < <(grep -nH -E '^[[:space:]]*- \[ \]' openspec/changes/archive/*/tasks.md 2>/dev/null | grep -vF '[human]' || true)

exit $bad
